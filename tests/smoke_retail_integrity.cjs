const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const app=fs.readFileSync('assets/app.js','utf8');
const elements=new Map();
const el=id=>{if(!elements.has(id))elements.set(id,{innerHTML:'',textContent:'',style:{},value:'',dataset:{},getContext(){return {id};},addEventListener(){}});return elements.get(id);};
const refs=JSON.parse(fs.readFileSync('data/reference_signals.json'));
refs.collection={...(refs.collection||{}),failures:['target: fixture collection failure']};
const sandbox={window:{addEventListener(){}},document:{getElementById:el,querySelectorAll:()=>[]},URL,console,fetch:async()=>{},setTimeout(){},clearTimeout(){},location:{hash:'#demand'}};
const ctx=vm.createContext(sandbox);
vm.runInContext(app.replace("window.addEventListener('DOMContentLoaded',init);", "window.test={state,renderDemand,renderRetailReferences,renderLogistics};"),ctx);
const test=sandbox.window.test;
test.state.reference=refs;
test.state.demand={countries:[{code:'US',name:'미국',amazon:'amazon.com'}],retailers:[{id:'ulta',name:'Ulta Beauty',country:'US',url:'https://www.ulta.com/brand/medicube'},{id:'target',name:'Target',country:'US',url:'https://www.target.com/'}],trends:[],amazon:[],retail:[]};
test.renderRetailReferences();
assert(!el('retail-signal-list').innerHTML.includes('104k+ bought'),'excluded badge must never be a numeric headline');
assert(el('retail-signal-list').innerHTML.includes('검증 제외'));
test.renderDemand();
const latestUlta=[...refs.retail,...refs.product_review_history].filter(x=>x.retailer==='ulta').map(x=>x.date).sort().at(-1);
assert(el('retailer-grid').innerHTML.includes('공개 지표 관찰 '+latestUlta),'reference data must feed retailer card');
assert(el('retailer-grid').innerHTML.includes('최근 자동 수집 실패'));
assert(el('demand-sources').innerHTML.includes('일부 실패'));
test.renderLogistics();
assert(el('offline-table').innerHTML.includes('약 20%'));
assert(!el('offline-table').innerHTML.includes('20~23'));
assert(el('offline-table').innerHTML.includes('비중환산')||el('offline-table').innerHTML.includes('추정치'));
const other=refs.regional_channels.regions.find(r=>r.name==='기타 해외');
assert.equal(other.q3,773.12);
for(const r of refs.regional_channels.regions.filter(r=>r.q3_share_pct!=null))assert.equal(r.q3,Math.round(refs.regional_channels.q3_total_revenue*r.q3_share_pct)/100);
assert(refs.regional_channels.sources.every(x=>x.url.startsWith('https://')));
console.log('PASS retail exclusion, reference freshness, partial failures and regional provenance');
